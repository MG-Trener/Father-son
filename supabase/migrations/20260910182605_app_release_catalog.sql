create or replace function public.get_latest_app_release(
  p_platform text default 'android',
  p_channel text default 'preview'
) returns table (
  version_name text,
  version_code integer,
  minimum_supported_code integer,
  title text,
  notes text,
  download_url text,
  published_at timestamptz
)
language sql
security invoker
stable
set search_path = pg_catalog, public
as $$
  select r.version_name, r.version_code, r.minimum_supported_code, r.title, r.notes, r.download_url, r.published_at
  from public.app_releases r
  where r.platform = p_platform
    and r.channel = p_channel
    and r.is_enabled = true
  order by r.version_code desc
  limit 1;
$$;

revoke all on function public.get_latest_app_release(text,text) from public;
grant execute on function public.get_latest_app_release(text,text) to anon, authenticated;
