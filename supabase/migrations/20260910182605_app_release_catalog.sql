create table if not exists public.app_releases (
  id bigint generated by default as identity primary key,
  platform text not null check (platform in ('android','ios')),
  channel text not null default 'preview' check (channel in ('preview','production')),
  version_name text not null,
  version_code integer not null check (version_code > 0),
  minimum_supported_code integer not null default 1 check (minimum_supported_code > 0),
  title text,
  notes text,
  download_url text,
  is_enabled boolean not null default true,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique(platform, channel, version_code),
  check (minimum_supported_code <= version_code),
  check (title is null or char_length(title) <= 120),
  check (notes is null or char_length(notes) <= 4000),
  check (download_url is null or char_length(download_url) <= 2000)
);

alter table public.app_releases enable row level security;
revoke all on table public.app_releases from public, anon, authenticated;
grant select on table public.app_releases to anon, authenticated;

create policy app_releases_read_enabled
on public.app_releases
for select
to anon, authenticated
using (is_enabled = true);

create index if not exists app_releases_latest_idx
on public.app_releases(platform, channel, version_code desc)
where is_enabled = true;

